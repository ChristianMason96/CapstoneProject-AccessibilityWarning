
console.log("Starting BullMQ worker...");

const { Worker } = require("bullmq");
const { spawn } = require("child_process");
const path = require("path");
const fs = require("fs");
const os = require("os");

const { connection } = require("./connection");
const pool = require("../../db");
const { getFile } = require("../services/storageService");

const projectRoot = path.join(__dirname, "..", "..", "..");

const worker = new Worker(
  "movie-processing",

  async (job) => {
    const {
      dbJobId,
      moviePath,
      storedFileName,
      fileReference
    } = job.data;

    console.log(
      `Processing job ${job.id}, database job ${dbJobId}`
    );

    let processingPath = moviePath;
    let temporaryDir = null;

    try {
      await pool.query(
        `UPDATE jobs
         SET status = 'processing',
             started_at = CURRENT_TIMESTAMP,
             completed_at = NULL,
             error_message = NULL
         WHERE id = $1`,
        [dbJobId]
      );

      // Download an S3 movie to a temporary local folder.
      // Python requires a local file path.
      if (fileReference?.provider === "s3") {
        temporaryDir = await fs.promises.mkdtemp(
          path.join(os.tmpdir(), "capstone-movie-")
        );

        const destinationPath = path.join(
          temporaryDir,
          path.basename(storedFileName)
        );

        processingPath = await getFile(
          fileReference,
          destinationPath
        );
      }

      const pythonScript = path.join(
        projectRoot,
        "worker",
        "process_movie.py"
      );

      const pythonCommand = process.env.PYTHON_BIN || "python";

      // Run the Python detection pipeline.
      await new Promise((resolve, reject) => {
        const python = spawn(
          pythonCommand,
          [pythonScript, processingPath],
          {
            cwd: projectRoot,
            stdio: "inherit"
          }
        );

        python.on("error", reject);

        python.on("close", code => {
          if (code === 0) {
            resolve();
          } else {
            reject(
              new Error(
                `Python processing failed (exit code ${code})`
              )
            );
          }
        });
      });

      // Read the result JSON generated by Python.
      const movieName = path.parse(storedFileName).name;

      const resultFile = path.join(
        projectRoot,
        "output",
        "results",
        `${movieName}_results.json`
      );

      if (!fs.existsSync(resultFile)) {
        throw new Error(
          `Results file not found: ${resultFile}`
        );
      }

      const parsed = JSON.parse(
        fs.readFileSync(resultFile, "utf-8")
      );

      const allWarnings = [
        ...(parsed.flash_warnings || []),
        ...(parsed.audio_warnings || [])
      ];

      // Store warnings and completed status
      // in one PostgreSQL transaction.
      const client = await pool.connect();

      try {
        await client.query("BEGIN");

        // Prevent duplicate warnings on retries.
        await client.query(
          `DELETE FROM warning_segments
           WHERE job_id = $1`,
          [dbJobId]
        );

        for (const warning of allWarnings) {
          await client.query(
            `INSERT INTO warning_segments
             (
               job_id,
               warning_type,
               start_time,
               end_time,
               severity,
               confidence,
               detection_mode,
               event_count
             )
             VALUES ($1, $2, $3, $4, $5, $6, $7, $8)`,
            [
              dbJobId,
              warning.warning_type,
              warning.start_time,
              warning.end_time,
              warning.severity,
              warning.confidence,
              warning.detection_mode || null,
              warning.event_count ?? 1
            ]
          );
        }

        await client.query(
          `UPDATE jobs
           SET status = 'completed',
               completed_at = CURRENT_TIMESTAMP,
               error_message = NULL
           WHERE id = $1`,
          [dbJobId]
        );

        await client.query("COMMIT");

      } catch (error) {
        try {
          await client.query("ROLLBACK");
        } catch (rollbackError) {
          console.error(
            "Could not roll back warnings:",
            rollbackError
          );
        }

        throw error;

      } finally {
        client.release();
      }

      console.log(
        `Completed job ${job.id} with ${allWarnings.length} warning segments.`
      );

      return { success: true };

    } finally {
      // Remove only temporary S3 downloads.
      // Never delete the original local upload.
      if (temporaryDir) {
        try {
          await fs.promises.rm(temporaryDir, {
            recursive: true,
            force: true
          });
        } catch (cleanupError) {
          console.error(
            "Could not clean temporary movie:",
            cleanupError
          );
        }
      }
    }
  },

  {
    connection,
    lockDuration: 600000,
    stalledInterval: 30000,
    maxStalledCount: 3
  }
);

// Mark failed jobs in PostgreSQL.
worker.on("failed", async (job, error) => {
  console.error("Worker job failed:", error);

  if (!job?.data?.dbJobId) {
    return;
  }

  try {
    await pool.query(
      `UPDATE jobs
       SET status = 'failed',
           error_message = $2,
           completed_at = CURRENT_TIMESTAMP
       WHERE id = $1`,
      [
        job.data.dbJobId,
        error.message
      ]
    );

  } catch (dbError) {
    console.error(
      "Could not save failed job status:",
      dbError
    );
  }
});

console.log("BullMQ worker is listening for jobs...");
